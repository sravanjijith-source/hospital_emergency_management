package hems.database;

import hems.dao.DoctorDao;
import hems.dao.PatientDao;
import hems.dao.SequenceDao;
import hems.dao.TreatmentRecordDao;
import hems.model.Doctor;
import hems.model.DoctorStatus;
import hems.model.Patient;
import hems.model.Severity;
import hems.model.TreatmentRecord;
import hems.model.TreatmentStatus;
import hems.service.DashboardStats;
import hems.service.HospitalSystem;
import hems.util.InvalidStateException;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

@Tag("db")
@DisplayName("Database-Backed Persistence & Transaction Integration Tests (hems_test)")
class HospitalSystemDatabaseTest {

    private static ConnectionProvider testConnectionProvider;
    private static PatientDao patientDao;
    private static DoctorDao doctorDao;
    private static TreatmentRecordDao treatmentRecordDao;
    private static SequenceDao sequenceDao;

    private HospitalSystem system;

    @BeforeAll
    static void initDatabase() {
        // Resolve test database URL
        String envUrl = System.getenv(DatabaseConfig.ENV_URL);
        String testUrl;
        if (envUrl != null && envUrl.contains("/hems")) {
            testUrl = envUrl.replace("/hems", "/hems_test");
        } else {
            testUrl = "jdbc:mysql://localhost:3306/hems_test?useSSL=false&allowPublicKeyRetrieval=true&serverTimezone=UTC";
        }

        String user = System.getenv(DatabaseConfig.ENV_USER);
        if (user == null || user.trim().isEmpty()) {
            user = "hems_user";
        }
        String password = System.getenv(DatabaseConfig.ENV_PASSWORD);

        DatabaseConfig testConfig = new DatabaseConfig(testUrl, user, password);
        testConnectionProvider = new ConnectionProvider(testConfig);

        patientDao = new PatientDao();
        doctorDao = new DoctorDao();
        treatmentRecordDao = new TreatmentRecordDao();
        sequenceDao = new SequenceDao();

        // Initialize schema in hems_test
        SchemaInitializer initializer = new SchemaInitializer(testConnectionProvider);
        initializer.initialize();
    }

    @BeforeEach
    void setUp() throws SQLException {
        cleanTestData();
        system = new HospitalSystem(patientDao, doctorDao, treatmentRecordDao, sequenceDao, testConnectionProvider);
    }

    @AfterEach
    void tearDown() throws SQLException {
        cleanTestData();
    }

    private void cleanTestData() throws SQLException {
        try (Connection conn = testConnectionProvider.getConnection();
             Statement stmt = conn.createStatement()) {
            stmt.execute("DELETE FROM emergency_visits");
            stmt.execute("DELETE FROM doctors");
            stmt.execute("DELETE FROM patients");
            stmt.execute("DELETE FROM id_sequences");
        }
    }

    @Test
    @DisplayName("Persist patient and doctor to MySQL and verify retrieval")
    void testPersistPatientAndDoctor() {
        TreatmentRecord visit = system.registerPatient("James Gordon", 52, Severity.HIGH);
        assertNotNull(visit);
        assertTrue(visit.getVisitId() > 0, "MySQL must generate an auto-increment visit ID");
        String patId = visit.getPatientId();
        assertEquals("P-0001", patId);

        Doctor doc = system.registerDoctor("Dr. Leslie Thompkins", 48, "Trauma Surgery", DoctorStatus.AVAILABLE);
        assertNotNull(doc);
        String docId = doc.getId();
        assertEquals("D-001", docId);

        // Verify direct from MySQL via DAOs
        try (Connection conn = testConnectionProvider.getConnection()) {
            Patient p = patientDao.findById(conn, patId);
            assertNotNull(p);
            assertEquals("James Gordon", p.getName());
            assertEquals(52, p.getAge());

            Doctor d = doctorDao.findById(conn, docId);
            assertNotNull(d);
            assertEquals("Dr. Leslie Thompkins", d.getName());
            assertEquals(DoctorStatus.AVAILABLE, d.getStatus());
        } catch (SQLException e) {
            fail("Database check failed: " + e.getMessage());
        }
    }

    @Test
    @DisplayName("Auto-generated IDs are unique and sequential in MySQL")
    void testUniqueAutoGeneratedIdsInDatabase() {
        TreatmentRecord v1 = system.registerPatient("First Person", 30, Severity.LOW);
        TreatmentRecord v2 = system.registerPatient("Second Person", 35, Severity.HIGH);
        assertNotEquals(v1.getPatientId(), v2.getPatientId());
        assertEquals("P-0001", v1.getPatientId());
        assertEquals("P-0002", v2.getPatientId());

        Doctor d1 = system.registerDoctor("Dr. One", 40, "General", DoctorStatus.AVAILABLE);
        Doctor d2 = system.registerDoctor("Dr. Two", 42, "Pediatrics", DoctorStatus.AVAILABLE);
        assertNotEquals(d1.getId(), d2.getId());
        assertEquals("D-001", d1.getId());
        assertEquals("D-002", d2.getId());
    }

    @Test
    @DisplayName("Transactional Assign Next Patient updates both visit and doctor atomically in MySQL")
    void testTransactionalAssignment() throws SQLException {
        Doctor doc = system.registerDoctor("Dr. Victor Fries", 45, "Cryogenics", DoctorStatus.AVAILABLE);
        TreatmentRecord visit = system.registerPatient("Harvey Dent", 38, Severity.CRITICAL);
        String docId = doc.getId();

        TreatmentRecord assigned = system.assignNextPatient();
        assertEquals(visit.getVisitId(), assigned.getVisitId());
        assertEquals(TreatmentStatus.IN_TREATMENT, assigned.getStatus());
        assertEquals(docId, assigned.getAssignedDoctorId());

        // Check database state directly
        try (Connection conn = testConnectionProvider.getConnection()) {
            Doctor dbDoc = doctorDao.findById(conn, docId);
            assertEquals(DoctorStatus.BUSY, dbDoc.getStatus());

            TreatmentRecord dbVisit = treatmentRecordDao.findById(conn, visit.getVisitId(), null);
            assertNotNull(dbVisit);
            assertEquals(TreatmentStatus.IN_TREATMENT, dbVisit.getStatus());
            assertEquals(docId, dbVisit.getAssignedDoctorId());
            assertNotNull(dbVisit.getStartTime());
        }
    }

    @Test
    @DisplayName("Transactional Complete Treatment sets COMPLETED and frees doctor in MySQL")
    void testTransactionalCompletion() throws SQLException {
        Doctor doc = system.registerDoctor("Dr. Pamela Isley", 35, "Toxicology", DoctorStatus.AVAILABLE);
        TreatmentRecord visit = system.registerPatient("Selina Kyle", 29, Severity.HIGH);
        String docId = doc.getId();

        system.assignNextPatient();

        TreatmentRecord completed = system.completeTreatment(visit.getVisitId());
        assertEquals(TreatmentStatus.COMPLETED, completed.getStatus());
        assertNotNull(completed.getEndTime());

        // Check database state directly
        try (Connection conn = testConnectionProvider.getConnection()) {
            Doctor dbDoc = doctorDao.findById(conn, docId);
            assertEquals(DoctorStatus.AVAILABLE, dbDoc.getStatus());

            TreatmentRecord dbVisit = treatmentRecordDao.findById(conn, visit.getVisitId(), null);
            assertEquals(TreatmentStatus.COMPLETED, dbVisit.getStatus());
            assertNotNull(dbVisit.getEndTime());
        }
    }

    @Test
    @DisplayName("Multi-visit patient history persists in MySQL and reads in reverse chronological order")
    void testMultiVisitHistoryInDatabase() {
        Doctor doc = system.registerDoctor("Dr. Thomas Wayne", 50, "Surgery", DoctorStatus.AVAILABLE);
        TreatmentRecord visit1 = system.registerPatient("Bruce Wayne", 34, Severity.MEDIUM);
        String patId = visit1.getPatientId();

        system.assignNextPatient();
        system.completeTreatment(visit1.getVisitId());

        // Second visit arrives later
        TreatmentRecord visit2 = system.createEmergencyVisit(patId, Severity.CRITICAL);
        assertTrue(visit2.getVisitId() > visit1.getVisitId());

        // Query history from MySQL
        List<TreatmentRecord> history = system.getPatientHistory(patId);
        assertEquals(2, history.size());
        assertEquals(visit2.getVisitId(), history.get(0).getVisitId(), "Most recent visit first");
        assertEquals(visit1.getVisitId(), history.get(1).getVisitId());
    }

    @Test
    @DisplayName("Restart recovery: rebuilding HospitalSystem from MySQL restores queue and doctor availability")
    void testRestartRecovery() {
        // Setup initial system state
        Doctor docA = system.registerDoctor("Dr. Charles", 45, "ER", DoctorStatus.AVAILABLE);
        Doctor docB = system.registerDoctor("Dr. Beverly", 40, "ER", DoctorStatus.AVAILABLE);

        TreatmentRecord p1 = system.registerPatient("Patient Low", 20, Severity.LOW);
        TreatmentRecord p2 = system.registerPatient("Patient Crit", 55, Severity.CRITICAL);
        TreatmentRecord p3 = system.registerPatient("Patient Med", 32, Severity.MEDIUM);

        // Assign p2 (CRITICAL)
        TreatmentRecord assigned = system.assignNextPatient();
        assertEquals(p2.getPatientId(), assigned.getPatientId());
        String assignedDocId = assigned.getAssignedDoctorId();
        String unassignedDocId = docA.getId().equals(assignedDocId) ? docB.getId() : docA.getId();

        // Simulate closing the app and starting a brand new instance
        HospitalSystem restartedSystem = new HospitalSystem(patientDao, doctorDao, treatmentRecordDao, sequenceDao, testConnectionProvider);
        restartedSystem.reloadFromDatabase();

        // Verify queue is restored with exact deterministic priority
        List<TreatmentRecord> restoredQueue = restartedSystem.getWaitingQueueSnapshot();
        assertEquals(2, restoredQueue.size());
        assertEquals(Severity.MEDIUM, restoredQueue.get(0).getSeverity(), "MEDIUM before LOW");
        assertEquals(Severity.LOW, restoredQueue.get(1).getSeverity());

        // Verify doctors restored
        Doctor busyDoc = restartedSystem.findDoctorById(assignedDocId);
        Doctor availDoc = restartedSystem.findDoctorById(unassignedDocId);
        assertEquals(DoctorStatus.BUSY, busyDoc.getStatus());
        assertEquals(DoctorStatus.AVAILABLE, availDoc.getStatus());

        // Verify dashboard counts match
        DashboardStats stats = restartedSystem.getDashboardStats();
        assertEquals(3, stats.getTotalPatients());
        assertEquals(3, stats.getTotalVisits());
        assertEquals(2, stats.getWaitingVisits());
        assertEquals(1, stats.getInTreatmentVisits());
        assertEquals(0, stats.getCompletedVisits());
    }

    @Test
    @DisplayName("Reconciliation resets BUSY doctors with no active visits back to AVAILABLE")
    void testReconciliation() throws SQLException {
        Doctor doc = system.registerDoctor("Dr. Inconsistent", 48, "ER", DoctorStatus.AVAILABLE);

        // Manually update doctor to BUSY in MySQL without an active visit
        try (Connection conn = testConnectionProvider.getConnection()) {
            doctorDao.updateStatus(conn, doc.getId(), DoctorStatus.BUSY);
        }

        // Reload and reconcile
        system.reloadFromDatabase();

        Doctor reloadedDoc = system.findDoctorById(doc.getId());
        assertEquals(DoctorStatus.AVAILABLE, reloadedDoc.getStatus(),
                "Reconciliation should fix orphaned BUSY doctor status");
    }

    @Test
    @DisplayName("Rollback leaves database completely untouched if assignment fails")
    void testAssignmentRollbackOnFailure() throws SQLException {
        Doctor doc = system.registerDoctor("Dr. Busy", 45, "ER", DoctorStatus.AVAILABLE);
        system.registerPatient("Waiting Patient", 30, Severity.CRITICAL);

        // Intentionally simulate a concurrent conflict: manually mark doctor OFF_DUTY in MySQL right before assignment
        try (Connection conn = testConnectionProvider.getConnection()) {
            doctorDao.updateStatus(conn, doc.getId(), DoctorStatus.OFF_DUTY);
        }

        // Assignment will fail when locking doctor in DB
        assertThrows(InvalidStateException.class, () -> system.assignNextPatient());

        // Verify visit is still WAITING in DB and was not corrupted
        try (Connection conn = testConnectionProvider.getConnection()) {
            List<TreatmentRecord> waiting = treatmentRecordDao.findWaitingVisits(conn, null);
            assertEquals(1, waiting.size());
            assertEquals(TreatmentStatus.WAITING, waiting.get(0).getStatus());
        }
    }
}
