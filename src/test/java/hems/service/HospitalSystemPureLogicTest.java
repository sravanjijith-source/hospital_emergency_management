@DisplayName("HospitalSystem Pure Logic Tests (In-Memory)")
class HospitalSystemPureLogicTest {

    private HospitalSystem system;

    @BeforeEach
    void setUp() {
        // Pure in-memory constructor for fast, decoupled unit testing
        system = new HospitalSystem();
    }

    @Nested
    @DisplayName("Registration & Input Validation")
    class RegistrationTests {

        @Test
        @DisplayName("Register valid patient and doctor successfully with auto-generated IDs")
        void testRegisterPatientAndDoctor() {
            TreatmentRecord visit = system.registerPatient("Alice Smith", 30, Severity.HIGH);
            assertNotNull(visit);
            assertEquals("P-0001", visit.getPatientId());
            assertEquals(Severity.HIGH, visit.getSeverity());
            assertEquals(TreatmentStatus.WAITING, visit.getStatus());

            Patient p = system.findPatientById("P-0001");
            assertNotNull(p);
            assertEquals("Alice Smith", p.getName());
            assertEquals(30, p.getAge());

            Doctor d = system.registerDoctor("Dr. John Watson", 45, "Emergency Care", DoctorStatus.AVAILABLE);
            assertNotNull(d);
            assertEquals("D-001", d.getId());
            assertEquals(DoctorStatus.AVAILABLE, d.getStatus());
        }

        @Test
        @DisplayName("Auto-generates sequential IDs for patients and doctors")
        void testAutoGeneratedIds() {
            TreatmentRecord v1 = system.registerPatient("Patient One", 25, Severity.LOW);
            TreatmentRecord v2 = system.registerPatient("Patient Two", 26, Severity.HIGH);
            assertEquals("P-0001", v1.getPatientId());
            assertEquals("P-0002", v2.getPatientId());

            Doctor d1 = system.registerDoctor("Dr. One", 35, "Cardio", DoctorStatus.AVAILABLE);
            Doctor d2 = system.registerDoctor("Dr. Two", 36, "Ortho", DoctorStatus.AVAILABLE);
            assertEquals("D-001", d1.getId());
            assertEquals("D-002", d2.getId());
        }

        @Test
        @DisplayName("Reject invalid patient age")
        void testInvalidPatientAge() {
            assertThrows(ValidationException.class, () ->
                    system.registerPatient("Negative Age", -1, Severity.LOW));
            assertThrows(ValidationException.class, () ->
                    system.registerPatient("Too Old", 121, Severity.LOW));
        }

        @Test
        @DisplayName("Reject invalid doctor age")
        void testInvalidDoctorAge() {
            assertThrows(ValidationException.class, () ->
                    system.registerDoctor("Too Young", 17, "ER", DoctorStatus.AVAILABLE));
            assertThrows(ValidationException.class, () ->
                    system.registerDoctor("Too Old", 91, "ER", DoctorStatus.AVAILABLE));
        }

        @Test
        @DisplayName("Reject blank patient name or null severity")
        void testInvalidPatientInput() {
            assertThrows(ValidationException.class, () ->
                    system.registerPatient("", 25, Severity.LOW));
            assertThrows(ValidationException.class, () ->
                    system.registerPatient("   ", 25, Severity.LOW));
            assertThrows(ValidationException.class, () ->
                    system.registerPatient("Valid Name", 25, null));
        }

        @Test
        @DisplayName("Reject blank doctor name, blank specialization, or null status")
        void testInvalidDoctorInput() {
            assertThrows(ValidationException.class, () ->
                    system.registerDoctor("", 35, "Cardiology", DoctorStatus.AVAILABLE));
            assertThrows(ValidationException.class, () ->
                    system.registerDoctor("Dr. Valid", 35, "   ", DoctorStatus.AVAILABLE));
            assertThrows(ValidationException.class, () ->
                    system.registerDoctor("Dr. Valid", 35, "Cardiology", null));
        }
    }

    @Nested
    @DisplayName("Priority Queue Ordering & Deterministic Tie-Breaking")
    class PriorityQueueTests {

        @Test
        @DisplayName("Queue orders strictly by severity: CRITICAL > HIGH > MEDIUM > LOW")
        void testSeverityOrdering() {
            system.registerPatient("Low Patient", 20, Severity.LOW);
            system.registerPatient("Medium Patient", 25, Severity.MEDIUM);
            system.registerPatient("Critical Patient", 50, Severity.CRITICAL);
            system.registerPatient("High Patient", 30, Severity.HIGH);

            List<TreatmentRecord> queue = system.getWaitingQueueSnapshot();
            assertEquals(4, queue.size());
            assertEquals(Severity.CRITICAL, queue.get(0).getSeverity());
            assertEquals(Severity.HIGH, queue.get(1).getSeverity());
            assertEquals(Severity.MEDIUM, queue.get(2).getSeverity());
            assertEquals(Severity.LOW, queue.get(3).getSeverity());
        }

        @Test
        @DisplayName("Queue breaks ties with earlier arrival time when severities match")
        void testArrivalTimeTieBreak() {
            LocalDateTime baseTime = LocalDateTime.of(2026, 10, 20, 10, 0, 0);

            TreatmentRecord visit1 = TreatmentRecord.newWaitingVisit("P-0001", Severity.HIGH, baseTime.plusMinutes(5));
            visit1.assignVisitId(101);
            TreatmentRecord visit2 = TreatmentRecord.newWaitingVisit("P-0002", Severity.HIGH, baseTime.plusMinutes(15));
            visit2.assignVisitId(102);

            assertTrue(TreatmentRecord.PRIORITY_ORDER.compare(visit1, visit2) < 0,
                    "Earlier arrival time should have higher priority (lower comparison value)");
        }

        @Test
        @DisplayName("Queue breaks final tie with lower visit ID when severity and arrival time match")
        void testVisitIdTieBreak() {
            LocalDateTime exactTime = LocalDateTime.of(2026, 10, 20, 10, 0, 0);

            TreatmentRecord visitA = TreatmentRecord.newWaitingVisit("P-0001", Severity.HIGH, exactTime);
            visitA.assignVisitId(10);
            TreatmentRecord visitB = TreatmentRecord.newWaitingVisit("P-0002", Severity.HIGH, exactTime);
            visitB.assignVisitId(20);

            assertTrue(TreatmentRecord.PRIORITY_ORDER.compare(visitA, visitB) < 0,
                    "Lower visit ID should be prioritized in deterministic tie-break");
        }
    }

    @Nested
    @DisplayName("Triage Assignment & Treatment Lifecycle")
    class AssignmentAndLifecycleTests {

        @Test
        @DisplayName("Assign next patient picks highest priority and marks doctor BUSY")
        void testAssignNextPatient() {
            Doctor doc = system.registerDoctor("Dr. House", 45, "Diagnostics", DoctorStatus.AVAILABLE);
            TreatmentRecord pLow = system.registerPatient("Low Patient", 20, Severity.LOW);
            TreatmentRecord pCrit = system.registerPatient("Critical Patient", 60, Severity.CRITICAL);

            TreatmentRecord assigned = system.assignNextPatient();
            assertEquals(pCrit.getPatientId(), assigned.getPatientId());
            assertEquals(TreatmentStatus.IN_TREATMENT, assigned.getStatus());
            assertNotNull(assigned.getStartTime());
            assertNotNull(assigned.getAssignedDoctor());
            assertEquals(doc.getId(), assigned.getAssignedDoctorId());

            Doctor updatedDoc = system.findDoctorById(doc.getId());
            assertEquals(DoctorStatus.BUSY, updatedDoc.getStatus());

            // Check queue has remaining LOW patient
            List<TreatmentRecord> queue = system.getWaitingQueueSnapshot();
            assertEquals(1, queue.size());
            assertEquals(pLow.getPatientId(), queue.get(0).getPatientId());
        }

        @Test
        @DisplayName("Assignment fails when no doctor is AVAILABLE and leaves queue untouched")
        void testAssignWithNoAvailableDoctor() {
            system.registerDoctor("Dr. Off", 40, "ER", DoctorStatus.OFF_DUTY);
            TreatmentRecord p = system.registerPatient("Alice", 30, Severity.CRITICAL);

            assertThrows(NoAvailableDoctorException.class, () -> system.assignNextPatient());

            // Verify queue is completely untouched
            List<TreatmentRecord> queue = system.getWaitingQueueSnapshot();
            assertEquals(1, queue.size());
            assertEquals(p.getPatientId(), queue.get(0).getPatientId());
            assertEquals(TreatmentStatus.WAITING, queue.get(0).getStatus());
        }

        @Test
        @DisplayName("Assigning on empty queue throws InvalidStateException")
        void testAssignOnEmptyQueue() {
            system.registerDoctor("Dr. Free", 40, "ER", DoctorStatus.AVAILABLE);
            assertThrows(InvalidStateException.class, () -> system.assignNextPatient());
        }

        @Test
        @DisplayName("Complete treatment sets COMPLETED and returns doctor to AVAILABLE")
        void testCompleteTreatment() {
            Doctor doc = system.registerDoctor("Dr. Free", 40, "ER", DoctorStatus.AVAILABLE);
            system.registerPatient("Alice", 30, Severity.CRITICAL);

            TreatmentRecord assigned = system.assignNextPatient();
            assertEquals(DoctorStatus.BUSY, system.findDoctorById(doc.getId()).getStatus());

            TreatmentRecord completed = system.completeTreatment(assigned.getVisitId());
            assertEquals(TreatmentStatus.COMPLETED, completed.getStatus());
            assertNotNull(completed.getEndTime());
            assertEquals(DoctorStatus.AVAILABLE, system.findDoctorById(doc.getId()).getStatus());
        }

        @Test
        @DisplayName("Cannot complete WAITING visit or complete visit twice")
        void testIllegalCompletion() {
            system.registerDoctor("Dr. Free", 40, "ER", DoctorStatus.AVAILABLE);
            TreatmentRecord waiting = system.registerPatient("Alice", 30, Severity.MEDIUM);

            // Cannot complete WAITING visit
            assertThrows(InvalidStateException.class, () -> system.completeTreatment(waiting.getVisitId()));

            // Now assign and complete once
            system.assignNextPatient();
            system.completeTreatment(waiting.getVisitId());

            // Cannot complete a second time
            assertThrows(InvalidStateException.class, () -> system.completeTreatment(waiting.getVisitId()));
        }

        @Test
        @DisplayName("Doctor status manual transitions: AVAILABLE <-> OFF_DUTY only")
        void testDoctorStatusTransitions() {
            Doctor doc = system.registerDoctor("Dr. Test", 40, "General", DoctorStatus.AVAILABLE);

            // AVAILABLE -> OFF_DUTY
            system.updateDoctorStatus(doc.getId(), DoctorStatus.OFF_DUTY);
            assertEquals(DoctorStatus.OFF_DUTY, doc.getStatus());

            // OFF_DUTY -> AVAILABLE
            system.updateDoctorStatus(doc.getId(), DoctorStatus.AVAILABLE);
            assertEquals(DoctorStatus.AVAILABLE, doc.getStatus());

            // Manual change to BUSY is forbidden
            assertThrows(InvalidStateException.class, () ->
                    system.updateDoctorStatus(doc.getId(), DoctorStatus.BUSY));
        }

        @Test
        @DisplayName("Cannot set BUSY doctor OFF_DUTY or AVAILABLE manually")
        void testBusyDoctorCannotChangeStatusManually() {
            Doctor doc = system.registerDoctor("Dr. Busy", 40, "ER", DoctorStatus.AVAILABLE);
            system.registerPatient("Alice", 30, Severity.CRITICAL);
            system.assignNextPatient();

            assertEquals(DoctorStatus.BUSY, system.findDoctorById(doc.getId()).getStatus());

            assertThrows(InvalidStateException.class, () ->
                    system.updateDoctorStatus(doc.getId(), DoctorStatus.OFF_DUTY));
            assertThrows(InvalidStateException.class, () ->
                    system.updateDoctorStatus(doc.getId(), DoctorStatus.AVAILABLE));
        }
    }

    @Nested
    @DisplayName("Multiple Visits & Patient History")
    class MultiVisitTests {

        @Test
        @DisplayName("Patient can have multiple visits over time, but only one open at a time")
        void testMultipleVisitsForSamePatient() {
            system.registerDoctor("Dr. Quick", 40, "ER", DoctorStatus.AVAILABLE);
            TreatmentRecord firstVisit = system.registerPatient("Bob", 45, Severity.MEDIUM);
            String bobId = firstVisit.getPatientId();

            // Trying to create a second emergency visit while first is WAITING must fail
            assertThrows(InvalidStateException.class, () ->
                    system.createEmergencyVisit(bobId, Severity.HIGH));

            // Assign and finish the first visit
            system.assignNextPatient();
            system.completeTreatment(firstVisit.getVisitId());

            // Now creating a new emergency visit for the same patient succeeds!
            TreatmentRecord secondVisit = system.createEmergencyVisit(bobId, Severity.HIGH);
            assertNotNull(secondVisit);
            assertNotEquals(firstVisit.getVisitId(), secondVisit.getVisitId());
            assertEquals(Severity.HIGH, secondVisit.getSeverity());

            List<TreatmentRecord> history = system.getPatientHistory(bobId);
            assertEquals(2, history.size());
        }
    }

    @Nested
    @DisplayName("Search & Dashboard Aggregations")
    class SearchAndDashboardTests {

        @Test
        @DisplayName("Search by ID and case-insensitive partial name")
        void testSearch() {
            TreatmentRecord p1 = system.registerPatient("John Doe", 35, Severity.LOW);
            TreatmentRecord p2 = system.registerPatient("Jane Doe", 28, Severity.MEDIUM);
            TreatmentRecord p3 = system.registerPatient("Alice Johnson", 40, Severity.HIGH);

            // Exact ID lookup
            assertNotNull(system.findPatientById(p1.getPatientId()));
            // Case-insensitive ID lookup
            assertNotNull(system.findPatientById(p1.getPatientId().toLowerCase()));
            assertNull(system.findPatientById("NON-EXISTENT"));

            // Partial name search
            List<Patient> does = system.findPatientsByName("doe");
            assertEquals(2, does.size());

            List<Patient> alice = system.findPatientsByName("ALICE");
            assertEquals(1, alice.size());
            assertEquals(p3.getPatientId(), alice.get(0).getId());
        }

        @Test
        @DisplayName("Dashboard stats correctly distinguish patients, visits, and doctor availability")
        void testDashboardStats() {
            system.registerDoctor("Dr. One", 40, "ER", DoctorStatus.AVAILABLE);
            system.registerDoctor("Dr. Two", 42, "ER", DoctorStatus.OFF_DUTY);

            system.registerPatient("Patient 1", 30, Severity.CRITICAL);
            system.registerPatient("Patient 2", 40, Severity.MEDIUM);

            // Assign first patient to available doctor
            system.assignNextPatient();

            DashboardStats stats = system.getDashboardStats();
            assertEquals(2, stats.getTotalPatients());
            assertEquals(2, stats.getTotalVisits());
            assertEquals(1, stats.getWaitingVisits());
            assertEquals(1, stats.getInTreatmentVisits());
            assertEquals(0, stats.getCompletedVisits());

            assertEquals(2, stats.getTotalDoctors());
            assertEquals(0, stats.getAvailableDoctors());
            assertEquals(1, stats.getBusyDoctors());
            assertEquals(1, stats.getOffDutyDoctors());
        }
    }
}
